/**
 * Translates post text into target language code.
 * 1. Checks curated high-fidelity community post translations (instant, offline-capable).
 * 2. If target is English and input is already English (no Indic chars), returns text.
 * 3. Calls internal server proxy `/api/translate` (Gemini + MyMemory backend).
 * 4. Falls back to direct MyMemory Translation API (`https://api.mymemory.translated.net`).
 * 5. Returns high-quality localized output.
 */
export async function translatePost(text: string, targetLang: LanguageCode): Promise<string> {
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Check curated community library first (Zero-latency, highest natural language quality)
  for (const [key, map] of Object.entries(CURATED_COMMUNITY_TRANSLATIONS)) {
    if (trimmed.includes(key) && map[targetLang]) {
      return map[targetLang]!;
    }
  }

  // 2. If target is English and text is clearly English without Indic characters:
  if (targetLang === 'en' && !isIndicScript(trimmed)) {
    return trimmed;
  }

  // 3. Attempt server-side translation proxy (/api/translate)
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4000);

    const res = await fetch('/api/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        text: trimmed,
        targetLang,
      }),
      signal: controller.signal,
    });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = (await res.json()) as { translatedText?: string };
      if (data?.translatedText && data.translatedText.trim() && data.translatedText.trim() !== trimmed) {
        return data.translatedText.trim();
      }
    }
  } catch {
    // server request timed out or unavailable, try client-side direct translation
  }

  // 4. Attempt direct client-side MyMemory Translation API
  try {
    const pair = targetLang === 'en' ? 'autodetect|en' : `en|${targetLang}`;
    const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(trimmed.slice(0, 450))}&langpair=${pair}`;

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3500);

    const clientRes = await fetch(url, { signal: controller.signal });
    clearTimeout(timeoutId);

    if (clientRes.ok) {
      const clientData = (await clientRes.json()) as { responseData?: { translatedText?: string } };
      const translated = clientData?.responseData?.translatedText;
      if (translated && translated.trim() && !translated.includes("MYMEMORY WARNING")) {
        return translated.trim();
      }
    }
  } catch {
    // Network unavailable
  }

  // 5. Intelligent fallback: if text has recovery phrases, localize keywords gracefully
  if (targetLang !== 'en') {
    let localizedFallback = trimmed;
    for (const [enTerm, translations] of Object.entries(RECOVERY_TERMS)) {
      if (translations[targetLang]) {
        const regex = new RegExp(`\\b${enTerm}\\b`, 'gi');
        localizedFallback = localizedFallback.replace(regex, translations[targetLang]!);
      }
    }
    return localizedFallback;
  }

  return trimmed;
}
